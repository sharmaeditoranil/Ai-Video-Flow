#!/usr/bin/env python3
"""
Builds the upload-ready server bundle for flow.aiphotoflow.in and syncs the public key into the app.

Secrets live outside the repository in ~/.ai-video-flow-admin/signing_key.json:
  - Ed25519 signing key (licenses are signed with it; the app only has the public half)
  - settings_key (encrypts API keys / payment secrets inside the server database)
  - initial_admin_password (first admin login only)

Output: dist/flow-server-bundle.zip  (index.php, .htaccess, config.php) - upload and extract on the server.
Usage:  python3 packaging/build_server_bundle.py [--local]   (--local also writes server/config.php for testing)
"""

import os
import sys
import json
import base64
import secrets
import zipfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SECRETS = os.path.expanduser("~/.ai-video-flow-admin/signing_key.json")
PUBLIC_KEY_PY = os.path.join(ROOT, "packages", "licensing", "public_key.py")
BUNDLE = os.path.join(ROOT, "dist", "flow-server-bundle.zip")


def load_secrets() -> dict:
    if not os.path.isfile(SECRETS):
        sys.exit(f"Missing {SECRETS}. Generate the signing key first (see README).")
    with open(SECRETS, "r", encoding="utf-8") as f:
        data = json.load(f)
    if "settings_key_b64" not in data:
        data["settings_key_b64"] = base64.b64encode(secrets.token_bytes(32)).decode()
        with open(SECRETS, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        os.chmod(SECRETS, 0o600)
    return data


def php_str(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def config_php(s: dict) -> str:
    return (
        "<?php\n// Generated by packaging/build_server_bundle.py - keep private, never commit.\nreturn [\n"
        f"    'signing_secret_key' => {php_str(s['sodium_secret_b64'])},\n"
        f"    'settings_key' => {php_str(s['settings_key_b64'])},\n"
        f"    'initial_admin_password' => {php_str(s['initial_admin_password'])},\n"
        "];\n"
    )


def main() -> None:
    s = load_secrets()

    with open(PUBLIC_KEY_PY, "w", encoding="utf-8") as f:
        f.write('"""Ed25519 public key that verifies license tokens signed by the license server."""\n\n'
                f'LICENSE_PUBLIC_KEY_B64 = "{s["public_b64"]}"\n')

    os.makedirs(os.path.dirname(BUNDLE), exist_ok=True)
    with zipfile.ZipFile(BUNDLE, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(ROOT, "server", "index.php"), "index.php")
        z.write(os.path.join(ROOT, "server", ".htaccess"), ".htaccess")
        z.writestr("config.php", config_php(s))
    os.chmod(BUNDLE, 0o600)

    if "--local" in sys.argv:
        local_cfg = os.path.join(ROOT, "server", "config.php")
        with open(local_cfg, "w", encoding="utf-8") as f:
            f.write(config_php(s))
        os.chmod(local_cfg, 0o600)

    print(f"Server bundle: {BUNDLE}")
    print(f"Public key synced to: {PUBLIC_KEY_PY}")


if __name__ == "__main__":
    main()
